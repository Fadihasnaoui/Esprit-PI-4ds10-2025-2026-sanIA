const shouldTranslateNode = (node) => {
  const parent = node.parentElement;
  if (!parent) return false;
  if (parent.closest('input, textarea, select, option, script, style, code, pre')) return false;
  if (parent.closest('[data-no-auto-translate="true"]')) return false;
  return true;
};

const applyStaticDomTranslations = (language) => {
  if (typeof document === 'undefined') return;
  const map = staticDomTranslations[language];
  if (!map) return;

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];
  let node = walker.nextNode();
  while (node) {
    nodes.push(node);
    node = walker.nextNode();
  }

  nodes.forEach((textNode) => {
    if (!shouldTranslateNode(textNode)) return;
    const key = normalizePhrase(textNode.nodeValue);
    if (!key || !map[key]) return;
    textNode.nodeValue = textNode.nodeValue.replace(key, map[key]);
  });
};

export const LanguageProvider = ({ children }) => {
  const [language, setLanguage] = useState(() => localStorage.getItem('sania-language') || 'fr');

  useEffect(() => {
    const meta = languages.find((item) => item.code === language) || languages[0];
    localStorage.setItem('sania-language', language);
    document.documentElement.setAttribute('lang', language);
    document.documentElement.setAttribute('dir', meta.dir);
  }, [language]);

  useEffect(() => {
    const run = () => applyStaticDomTranslations(language);
    const id = window.setTimeout(run, 0);
    const observer = new MutationObserver(() => window.requestAnimationFrame(run));
    observer.observe(document.body, { childList: true, subtree: true });
    return () => {
      window.clearTimeout(id);
      observer.disconnect();
    };
  }, [language]);

  const value = useMemo(() => {
    const t = (key, vars) => {
      const translated =
        getByPath(translations[language], key) ??
        getByPath(fallbackTranslations[language], key) ??
        getByPath(translations.fr, key) ??
        getByPath(fallbackTranslations.fr, key) ??
        key;
      return interpolate(translated, vars);
    };

    return {
      language,
      setLanguage,
      languages,
      dir: (languages.find((item) => item.code === language) || languages[0]).dir,
      t,
    };
  }, [language]);

  return (
    <I18nContext.Provider value={value}>
      <React.Fragment key={language}>{children}</React.Fragment>
    </I18nContext.Provider>
  );
};

export const useTranslation = () => {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useTranslation must be used inside LanguageProvider');
  return ctx;
};
