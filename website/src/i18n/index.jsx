const getByPath = (source, path) =>
  path.split('.').reduce((value, key) => (value && value[key] !== undefined ? value[key] : undefined), source);

const interpolate = (value, vars = {}) => {
  if (Array.isArray(value)) {
    return value.map((item) => interpolate(item, vars));
  }
  if (value && typeof value === 'object') {
    return value;
  }
  return String(value).replace(/\{(\w+)\}/g, (_, key) => (vars[key] ?? ''));
};

const normalizePhrase = (value) => String(value || '').replace(/\s+/g, ' ').trim();

